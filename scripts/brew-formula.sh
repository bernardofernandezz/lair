#!/bin/sh
# Prints the Homebrew formula for a release, from its SHA256SUMS. Only builds the release has are listed.
#   scripts/brew-formula.sh v1.1.0 SHA256SUMS > Formula/lair.rb
set -eu
tag=$1
sums=$2
base=https://github.com/bernardofernandezz/lair/releases/download/$tag

# One url/sha256 pair for an asset, or nothing when this release doesn't have it.
asset() {
  sha=$(awk -v f="$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$sha" ] && printf '      url "%s/%s.tar.gz"\n      sha256 "%s"\n' "$base" "$1" "$sha"
  return 0
}

block() {
  body=$(asset "$2")
  [ -n "$body" ] && printf '    %s do\n%s\n    end\n' "$1" "$body"
  return 0
}

cat <<RUBY
# Generated by scripts/brew-formula.sh on every release; edit the script, not this file.
class Lair < Formula
  desc "Your own AI on your own hardware: local GGUF models, web chat, agent and APIs"
  homepage "https://github.com/bernardofernandezz/lair"
  version "${tag#v}"
  license "MIT"

  on_macos do
$(block on_arm lair-macos-arm64)
  end

  on_linux do
$(block on_intel lair-linux-x86_64-cpu)
$(block on_arm lair-linux-arm64-cpu)
  end

  def install
    bin.install "lair"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/lair --version")
  end
end
RUBY
